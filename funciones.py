# Ejercicio 1 — Suma de dos números (se usan en el orden en que se pasan)

# Función nombrada
def suma(a, b):
    return a + b

# Función anónima
suma_lambda = lambda a, b: a + b

print("Ejercicio 1")
print(suma(3, 5))
print(suma_lambda(3, 5))
